// Turns the owner's filled-in exercise audit sheet (exercise-library-audit-*.xlsx) into src/lib/session-engine/overrides.ts.
// Run from this repo's root:  NODE_PATH=C:/Users/conor/gym-app-batch/node_modules node scripts/import-exercise-audit.cjs <path-to-xlsx>
// Only cells the owner filled in become overrides; blank cells keep the engine's own rules.
const ExcelJS = require("exceljs");
const fs = require("fs");
const path = require("path");

const AREA = { ankle: "ankle", knee: "knee", hip: "hip", back: "lower_back", "lower back": "lower_back", lowerback: "lower_back", shoulder: "shoulder", elbow: "elbow", wrist: "wrist", neck: "neck" };
const text = (c) => (c == null ? "" : String(c.text ?? c).trim());

(async () => {
  const file = process.argv[2];
  if (!file) throw new Error("Pass the path to the audit xlsx.");
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(file);
  const overrides = {};
  for (const ws of wb.worksheets) {
    if (ws.name === "Read me") continue;
    const head = {};
    ws.getRow(1).eachCell((cell, n) => (head[text(cell).toLowerCase()] = n));
    const col = (prefix) => Object.entries(head).find(([h]) => h.startsWith(prefix))?.[1];
    const c = { level: col("right level"), preg: col("pregnancy"), inj: col("injury areas"), grip: col("grip demand"), impact: col("impact"), spine: col("spine"), hard: col("hardness"), staple: col("classic staple") };
    ws.eachRow((row, i) => {
      if (i === 1) return;
      const name = text(row.getCell(1)).toLowerCase();
      if (!name) return;
      const o = {};
      const level = c.level ? text(row.getCell(c.level)).toLowerCase() : "";
      if (["beginner", "intermediate", "advanced"].includes(level)) o.level = level;
      if (level === "remove") o.hidden = true;
      const preg = c.preg ? text(row.getCell(c.preg)).toLowerCase() : "";
      if (preg.startsWith("ok")) o.pregnancy = "ok";
      else if (preg.startsWith("mod")) o.pregnancy = "modify";
      else if (preg.startsWith("avoid")) o.pregnancy = "avoid";
      const inj = c.inj ? text(row.getCell(c.inj)).toLowerCase() : "";
      if (inj) o.avoidFor = [...new Set(inj.split(/[,;/]+/).map((x) => AREA[x.trim()]).filter(Boolean))];
      const grip = c.grip ? text(row.getCell(c.grip)).toLowerCase() : "";
      if (grip) o.grip = grip.startsWith("none") ? 0 : grip.startsWith("low") ? 1 : grip.startsWith("med") ? 2 : grip.startsWith("high") ? 3 : undefined;
      const impact = c.impact ? text(row.getCell(c.impact)).toLowerCase() : "";
      if (impact) o.impact = impact.startsWith("none") ? 0 : impact.startsWith("low") ? 1 : impact.startsWith("high") ? 2 : undefined;
      const spine = c.spine ? text(row.getCell(c.spine)).toLowerCase() : "";
      if (spine) o.spineLoaded = spine.startsWith("y");
      const hard = c.hard ? Number(text(row.getCell(c.hard))) : NaN;
      if (hard >= 1 && hard <= 5) o.hardness = hard;
      const staple = c.staple ? text(row.getCell(c.staple)).toLowerCase() : "";
      if (staple) o.staple = staple.startsWith("y") ? 3 : -2;
      for (const k of Object.keys(o)) if (o[k] === undefined) delete o[k];
      if (Object.keys(o).length) overrides[name] = o;
    });
  }
  const body = `// Per-exercise corrections from the owner's audit of the exercise library, keyed by lower-case exercise name. Anything set here beats the rules in\n// flags.ts. Generated by scripts/import-exercise-audit.cjs from ${path.basename(file)}; do not edit by hand.\n\nimport type { ExerciseFlags } from "./types";\n\nexport type FlagOverride = Partial<Pick<ExerciseFlags, "level" | "hardness" | "grip" | "impact" | "spineLoaded" | "avoidFor" | "pregnancy" | "staple" | "hidden">>;\n\nexport const FLAG_OVERRIDES: Record<string, FlagOverride> = ${JSON.stringify(overrides, null, 2)};\n`;
  fs.writeFileSync(path.join(__dirname, "..", "src", "lib", "session-engine", "overrides.ts"), body);
  console.log(`Wrote ${Object.keys(overrides).length} overrides.`);
})();
